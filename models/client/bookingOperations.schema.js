const mongoose = require("mongoose");
const schema = new mongoose.Schema({
  _id: { type: String, required: true },
  eventCenter: { type: mongoose.Schema.Types.ObjectId, ref: "EventCenter", required: true, index: true },
  bookingId: { type: String, required: true },
  revision: { type: Number, default: 0 },
  customerId: { type: mongoose.Schema.Types.ObjectId, ref: "User", index: true },
  claimHash: { type: String, select: false }, claimExpiresAt: Date,
  refundAccount: { accountName: String, accountNumber: String, bankCode: String, updatedBy: { type: mongoose.Schema.Types.ObjectId, ref: "User" }, updatedAt: Date },
  refunds: [{ _id: false, id: String, amountMinor: Number, reason: String,
    settlement: { id: String, method: String, preparedAt: Date, bankDetails: { accountName: String, accountNumber: String, bankCode: String } },
    receipt: { publicId: String, format: String, uploadedAt: Date, settlementId: String },
    status: { type: String, enum: ["APPROVED", "SENT", "CONFIRMED"] }, approvedAt: Date, sentAt: Date, confirmedAt: Date,
    approvedBy: { type: mongoose.Schema.Types.ObjectId, ref: "User" }, confirmedBy: { type: mongoose.Schema.Types.ObjectId, ref: "User" }, confirmationEvidence: String }],
  bookingSnapshot: mongoose.Schema.Types.Mixed,
  openingPaidMinor: { type: Number, default: 0 },
  agreedPrice: { amount: Number, currency: String },
  rescheduleBuyerFeesMinor: { type: Number, default: 0 },
  rescheduleAdjustment: { type: Boolean, default: false },
  paymentDueDate: Date,
  eventPurpose: { type: String, maxlength: 200 },
  guestCount: { type: Number, min: 0 },
  seating: { type: String, maxlength: 500 },
  clientRequests: { type: String, maxlength: 2000 },
  privateNotes: { type: String, maxlength: 4000 },
  payments: [{ _id: false, id: String, kind: { type: String, enum: ["PAYMENT", "REFUND", "SECURITY_DEPOSIT", "SECURITY_RETURN"] },
    refundId: String, platformFeeMinor: Number, amountMinor: Number, method: String, reference: String, reason: String,
    at: Date, actor: { type: mongoose.Schema.Types.ObjectId, ref: "User" } }],
  handovers: [{ _id: false, sessionId: String, checkedOutAt: Date, cleaned: Boolean, damageNotes: String, overtimeMinutes: Number,
    actor: { type: mongoose.Schema.Types.ObjectId, ref: "User" } }],
  audit: [{ _id: false, action: String, at: Date, reason: String, actor: { type: mongoose.Schema.Types.ObjectId, ref: "User" } }],
}, { timestamps: true });
schema.index({ eventCenter: 1, bookingId: 1 }, { unique: true });
module.exports = mongoose.model("BookingOperations", schema);
